// Builds the dotted map of Europe for the contact section.
//
//   pnpm map
//
// Samples a square grid over Europe against Natural Earth country shapes (world-atlas, 1:50m) and
// writes src/app/components/europe-map.data.ts: two SVG paths of zero-length segments (one per
// dot, drawn with round caps), one for Spain and one for the rest of Europe, plus a pin position.
import type { Geometry, Position } from 'geojson';
import { readFile, writeFile } from 'node:fs/promises';
import { createRequire } from 'node:module';
import { feature } from 'topojson-client';
import type { GeometryCollection, Topology } from 'topojson-specification';

type Point = readonly [lon: number, lat: number];

const require = createRequire(import.meta.url);
const world = JSON.parse(await readFile(require.resolve('world-atlas/countries-50m.json'), 'utf8')) as Topology<{
  countries: GeometryCollection;
}>;
const countries = feature(world, world.objects.countries).features;

/** Overseas territories far outside the frame (French Guiana, the Canaries and so on) are skipped by the bounds. */
const BOUNDS = { west: -24, east: 44, north: 57, south: 34 } as const;
/** Longitude degrees shrink with latitude; at 47°N one is about 0.68 of a latitude degree. */
const LON_SCALE = Math.cos((47 * Math.PI) / 180);
/** Distance between dots, in latitude degrees. */
const STEP = 0.56;
const UNIT = 10;
/** ISO 3166-1 numeric code, as world-atlas uses for feature ids. */
const SPAIN = '724';

const project = (lon: number, lat: number): [number, number] => [
  Math.round((lon - BOUNDS.west) * LON_SCALE * UNIT * 10) / 10,
  Math.round((BOUNDS.north - lat) * UNIT * 10) / 10,
];

function inRing([lon, lat]: Point, ring: readonly Position[]): boolean {
  let hit = false;
  for (let i = 0, j = ring.length - 1; i < ring.length; j = i++) {
    const [xi = 0, yi = 0] = ring[i]!;
    const [xj = 0, yj = 0] = ring[j]!;
    if (yi > lat !== yj > lat && lon < ((xj - xi) * (lat - yi)) / (yj - yi) + xi) hit = !hit;
  }
  return hit;
}

function inGeometry(point: Point, geometry: Geometry): boolean {
  const polygons =
    geometry.type === 'Polygon' ? [geometry.coordinates] : geometry.type === 'MultiPolygon' ? geometry.coordinates : [];
  return polygons.some(([outer = [], ...holes]) => inRing(point, outer) && !holes.some(hole => inRing(point, hole)));
}

const candidates = countries.filter(country => country.geometry);
const spain: [number, number][] = [];
const europe: [number, number][] = [];
for (let lat: number = BOUNDS.north; lat >= BOUNDS.south; lat -= STEP) {
  for (let lon: number = BOUNDS.west; lon <= BOUNDS.east; lon += STEP / LON_SCALE) {
    const owner = candidates.find(country => inGeometry([lon, lat], country.geometry));
    if (!owner) continue;
    (owner.id === SPAIN ? spain : europe).push(project(lon, lat));
  }
}

const path = (points: readonly (readonly [number, number])[]) => points.map(([x, y]) => `M${x} ${y}h0`).join('');
const [width, height] = project(BOUNDS.east, BOUNDS.south);
// Centre of mainland Spain, near Madrid.
const [pinX, pinY] = project(-3.7, 40.2);

await writeFile(
  'src/app/components/europe-map.data.ts',
  `// Generated by scripts/europe-map.ts from Natural Earth (world-atlas). Do not edit by hand.\n` +
    `export const EUROPE_MAP = {\n` +
    `  width: ${width},\n  height: ${height},\n  pin: { x: ${pinX}, y: ${pinY} },\n` +
    `  spain: '${path(spain)}',\n  europe: '${path(europe)}',\n} as const;\n`,
);
console.log(`Europe map: ${europe.length} dots, Spain ${spain.length} dots, ${width}×${height}`);
